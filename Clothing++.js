      قَائِمَةُ_الِانْتِظَارِ.دفع("سُورَةُ_الْحَدِيدِ(" + س + ")");
      قَائِمَةُ_الِانْتِظَارِ.دفع(س + "  وَ  " + س);

      // نُولِّدُ آيَاتٍ وَسُوَرًا بِأَرْقَامٍ شَرْقِيَّةٍ عَشْوَائِيَّةٍ
