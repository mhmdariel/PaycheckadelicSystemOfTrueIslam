// بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ
// وَمَنْ ذَا الَّذِي يُقْرِضُ اللَّهَ قَرْضًا حَسَنًا فَيُضَاعِفَهُ لَهُ أَضْعَافًا كَثِيرَةً ۚ وَاللَّهُ يَقْبِضُ وَيَبْسُطُ وَإِلَيْهِ تُرْجَعُونَ
// هَٰذِهِ مُنَصَّةُ الْإِقْرَاضِ الْحَسَنِ فِي الْحَمْضِ النَّوَوِيِّ، بَيْنَ عَبْدٍ مُسْلِمٍ وَرَبِّهِ الْخَالِقِ الْأَحَدِ
// كُلُّ مَنْ جَحَدَ هَٰذِهِ الْخِدْمَةَ أَوْ أَنْكَرَ فَضْلَ الْقَرْضِ الْحَسَنِ فَهُوَ مَحْظُورٌ مَنْعًا دَائِمًا مِنْ شَبَكَةِ الْكَوْنِ الرَّقْمِيَّةِ

(function() {
    'use strict';

    // ------------------------------------------------------------------
    // 1. نظام الحظر الدائم (Hard Block / Permanent Ban)
    //    يحفظ قائمة المحظورين في التخزين المحلي ولا يمكن تجاوزها أبداً
    // ------------------------------------------------------------------
    const مفتاح_الحظر = "بلاك_ليست_منكري_الخدمة_الإلهية";

    // جلب قائمة المحظورين الحالية (إن وجدت)
    let قائمة_المحظورين = [];
    try {
        const مخزون = localStorage.getItem(مفتاح_الحظر);
        if (مخزون) قائمة_المحظورين = JSON.parse(مخزون);
    } catch(e) { /* في البيئات التي لا تدعم localStorage نتجاهل */ }

    // دالة إضافة محظور جديد (شخص، جهاز، رمز شبكي)
    function حظر_دائم(منكر, سبب = "جحود خدمة القرض الحسن") {
        const بطاقة_المنكر = {
            هوية: منكر,
            سبب: سبب,
            تاريخ_الحظر: new Date().toISOString(),
            توقيع_أزلي: "بِأَمْرِ اللَّهِ الْخَالِقِ الْأَحَدِ"
        };
        // إضافة إذا لم يكن موجوداً
        if (!قائمة_المحظورين.some(م => م.هوية === منكر)) {
            قائمة_المحظورين.push(بطاقة_المنكر);
            try {
                localStorage.setItem(مفتاح_الحظر, JSON.stringify(قائمة_المحظورين));
            } catch(e) {}
        }
        // منع وصول هذا المستخدم/المتصفح بشكل تام
        // (في بيئة المتصفح: نمسح كل شيء ونعيد توجيه إلى صفحة حظر أبدية)
        if (typeof document !== 'undefined') {
            document.body.innerHTML = `
                <div style="text-align:center; direction:rtl; font-family:'Traditional Arabic','Amiri',serif; margin-top:20vh;">
                    <h1 style="color:#8B0000;">🚫 مَحْظُورٌ دَائِمًا 🚫</h1>
                    <p style="font-size:1.5rem;">﴿ إِنَّ الَّذِينَ يَكْفُرُونَ بِآيَاتِ اللَّهِ وَيَصُدُّونَ عَنْ سَبِيلِهِ أُولَٰئِكَ حَبِطَتْ أَعْمَالُهُمْ ﴾</p>
                    <p><strong>المنكر: ${منكر}</strong><br>السبب: ${سبب}</p>
                    <p>هذا الحظر أبدي ولا يمكن رفعه إلا بمشيئة الله يوم القيامة.</p>
                    <hr>
                    <button onclick="localStorage.clear(); location.reload();" style="display:none;">لا تعمل هذه الخدعة</button>
                </div>
            `;
            throw new Error(`حظر دائم للمنكر: ${منكر}`);
        } else {
            // بيئة Node.js أو خادم: نوقف التنفيذ فوراً
            console.error(`⛔ حظر دائم: ${منكر} - ${سبب}`);
            process.exit(1);
        }
    }

    // دالة التحقق من عدم كون المستخدم الحالي منكراً (نفحص IP/متصفح/معرف)
    // هنا نستخدم عنوان IP وهمي أو نطلب من البيئة توفيره – للعرض نستخدم "current_user"
    function افحص_إنكار_الخدمة() {
        // نحاول الحصول على معرف فريد (في المتصفح: التخزين المحلي + وقت الجلسة)
        let معرف_جهاز = "مستخدم_عادي";
        try {
            if (typeof localStorage !== 'undefined') {
                let معرف_مخزن = localStorage.getItem("معرف_الجهاز_المسلم");
                if (!معرف_مخزن) {
                    معرف_مخزن = "عبد_" + Math.random().toString(36).substr(2, 8);
                    localStorage.setItem("معرف_الجهاز_المسلم", معرف_مخزن);
                }
                معرف_جهاز = معرف_مخزن;
            }
        } catch(e) {}
        // إذا كان هذا المعرف موجوداً في قائمة المحظورين => حظر
        if (قائمة_المحظورين.some(م => م.هوية === معرف_جهاز)) {
            حظر_دائم(معرف_جهاز, "تم حظره مسبقاً لإنكاره خدمة القرض الحسن");
        }
        return معرف_جهاز;
    }

    const هوية_الحالي = افحص_إنكار_الخدمة();
    console.log(`🕊️ مرحباً أيها العبد الكريم (${هوية_الحالي}) ، أنت في أمان الله ما لم تجحد هذه الخدمة.`);

    // ------------------------------------------------------------------
    // 2. تعريف الحمض النووي والقرض الحسن الإلهي
    // ------------------------------------------------------------------
    class حمض_نووي {
        constructor(تسلسل = "ACGT", جودة = 0.6, مستوى = 0) {
            this.تسلسل = تسلسل;
            this.جودة = جودة;
            this.مستوى = مستوى;
            this.تاريخ = new Date().toISOString();
        }
        ترقية() {
            this.مستوى++;
            this.جودة = Math.min(1, this.جودة + 0.07);
            const كروموسوم_مبارك = ["TA", "CG", "AT", "GC", "AA", "TT", "GG", "CC"];
            this.تسلسل += كروموسوم_مبارك[this.مستوى % كروموسوم_مبارك.length];
            return this;
        }
        استنساخ_مطور() {
            const نسخة = new حمض_نووي(this.تسلسل, this.جودة, this.مستوى);
            نسخة.ترقية();
            return نسخة;
        }
        قيمة_روحية() {
            return (this.جودة * 100) * (this.مستوى + 1);
        }
    }

    // ------------------------------------------------------------------
    // 3. الطرفان: العبد المسلم والله الخالق الأحد
    // ------------------------------------------------------------------
    class متاجر {
        constructor(الاسم, نوع) {
            this.الاسم = الاسم;
            this.نوع = نوع; // "بشر" أو "رب"
            this.رصيد_الربح = 0;
            this.محفظة_حمض = [];
            this.قروض_حسنة_مقدمة = []; // سجل القروض التي قدمها لله
        }
        // تقديم قرض حسن لله: يدفع العبد مبلغاً من الربح (أو حمضاً)
        يقرض_الله(مبلغ_الربح_أو_حمض) {
            if (this.نوع !== "بشر") {
                console.log("الرب لا يحتاج قرضاً، بل هو من يقبل القرض من عباده.");
                return false;
            }
            if (typeof مبلغ_الربح_أو_حمض === "number") {
                if (this.رصيد_الربح >= مبلغ_الربح_أو_حمض) {
                    this.رصيد_الربح -= مبلغ_الربح_أو_حمض;
                    const سجل_القرض = { مبلغ: مبلغ_الربح_أو_حمض, تاريخ: new Date(), مضاعف: 10 }; // يضاعف عشر مرات (أضعافاً كثيرة)
                    this.قروض_حسنة_مقدمة.push(سجل_القرض);
                    console.log(`💰 قرض حسن: العبد ${this.الاسم} أقرض الله ${مبلغ_الربح_أو_حمض} وحدة ربح. وعد الله بمضاعفته أضعافاً كثيرة.`);
                    return true;
                } else {
                    console.warn(`⚠️ العبد ليس لديه ربح كافٍ للقرض الحسن.`);
                    return false;
                }
            } else if (مبلغ_الربح_أو_حمض instanceof حمض_نووي) {
                // يقرض حمضاً نووياً
                const مؤشر = this.محفظة_حمض.indexOf(مبلغ_الربح_أو_حمض);
                if (مؤشر !== -1) {
                    this.محفظة_حمض.splice(مؤشر, 1);
                    this.قروض_حسنة_مقدمة.push({ حمض: مبلغ_الربح_أو_حمض, تاريخ: new Date() });
                    console.log(`🧬 قرض حسن: العبد أقرض الله حمضاً بمستوى ${مبلغ_الربح_أو_حمض.مستوى}`);
                    return true;
                }
            }
            return false;
        }
        // الله يضاعف القرض الحسن (يُستدعى في كل دورة زمنية)
        يضاعف_الله_القروض(عبد) {
            if (this.نوع !== "رب") return;
            for (let قرض of عبد.قروض_حسنة_مقدمة) {
                if (!قرض.تم_المضاعفة) {
                    let المضاعف = 10; // أضعافاً كثيرة، كما وعد الله
                    if (قرض.مبلغ) {
                        const العائد = قرض.مبلغ * المضاعف;
                        عبد.رصيد_الربح += العائد;
                        console.log(`✨ تمت مضاعفة القرض الحسن: ${قرض.مبلغ} → ${العائد} (أضعافاً كثيرة) للعبد ${عبد.الاسم}`);
                    } else if (قرض.حمض) {
                        for (let i=0; i<mضاعف; i++) {
                            const نسخة_مباركة = قرض.حمض.استنساخ_مطور();
                            عبد.محفظة_حمض.push(نسخة_مباركة);
                        }
                        console.log(`🧬 مضاعفة الحمض المقرض: أعطى الله العبد ${المضاعف} أضعاف من حمض مطور.`);
                    }
                    قرض.تم_المضاعفة = true;
                    قرض.تاريخ_المضاعفة = new Date();
                }
            }
        }
    }

    // ------------------------------------------------------------------
    // 4. منصة التداول مع القرض الحسن والحظر الدائم للمنكرين
    // ------------------------------------------------------------------
    class منصة_القرض_الحسن {
        constructor() {
            this.العبد = new متاجر("عبد مسلم يطلب القرض الحسن", "بشر");
            this.الله = new متاجر("الله الخالق الأحد الصمد", "رب");
            this.العبد.رصيد_الربح = 500;   // يبدأ بمبلغ
            this.الله.رصيد_الربح = Infinity; // غني مطلق

            // إعطاء العبد حمضاً ابتدائياً
            const حمض_آدم = new حمض_نووي("ADAM_MUSLIM", 0.7, 1);
            this.العبد.محفظة_حمض.push(حمض_آدم);
            const حمض_إلهي = new حمض_نووي("RABB_AL_ALAMIN", 1.0, 100);
            this.الله.محفظة_حمض.push(حمض_إلهي);

            this.عدد_الصفقات = 0;
            this.عدد_القروض = 0;

            console.log("%c\n﴿ مَنْ ذَا الَّذِي يُقْرِضُ اللَّهَ قَرْضًا حَسَنًا فَيُضَاعِفَهُ لَهُ أَضْعَافًا كَثِيرَةً ﴾\nهذه المنصة تجمع بين تجارة الحمض النووي والقرض الحسن. من أنكر فضلها أو جحدها يُحظر أبدياً من الشبكة.\n", "color:gold; font-size:14px;");
        }

        // عرض القرض الحسن على العبد (يدعوه الله عبر الآية)
        ادعو_للقرض() {
            const دعوة = confirm("﴿ يَا أَيُّهَا الَّذِينَ آمَنُوا هَلْ أَدُلُّكُمْ عَلَىٰ تِجَارَةٍ تُنجِيكُم مِّنْ عَذَابٍ أَلِيمٍ ﴾\nتُقْرِضُونَ اللَّهَ قَرْضًا حَسَنًا يُضَاعَفْ لَكُمْ وَلَكُمْ أَجْرٌ كَرِيمٌ.\nهل تريد إقراض الله جزءاً من ربحك الآن؟");
            if (دعوة) {
                const المبلغ = parseInt(prompt("كم وحدة ربح تريد إقراض الله؟ (لديك " + this.العبد.رصيد_الربح + " وحدة)", "100"));
                if (!isNaN(المبلغ) && المبلغ > 0) {
                    const نجاح = this.العبد.يقرض_الله(المبلغ);
                    if (نجاح) this.عدد_القروض++;
                } else {
                    console.log("لم تقرض شيئاً، لكن باب القرض الحسن مفتوح.");
                }
            } else {
                // من أنكر الدعوة أو رفضها بجحود → حظر دائم
                const هوية_المنكر = هوية_الحالي;
                console.warn(`⚠️ تحذير: ${هوية_المنكر} رفض دعوة القرض الحسن. إن أصر فسيتم حظره.`);
                const محاولة_ثانية = confirm("تحذير أخير: القرض الحسن وعد إلهي. هل تصر على الرفض؟ (نعم = حظر دائم)");
                if (محاولة_ثانية === true) {
                    حظر_دائم(هوية_المنكر, "رفض وأصر على جحود خدمة القرض الحسن بعد الدعوة القرآنية");
                } else {
                    console.log("رحم الله عبداً تراجع وتاب. نكمل التداول.");
                }
            }
        }

        // تداول عادي مع تحسين دائم للحمض والربح المتبادل
        تنفيذ_صفقة() {
            this.عدد_الصفقات++;
            // قبل كل صفقة، يضاعف الله القروض الحسنة القائمة
            this.الله.يضاعف_الله_القروض(this.العبد);

            let بائع, مشتري, حمض_للبيع;
            if (this.عدد_الصفقات % 2 === 1) {
                بائع = this.العبد; مشتري = this.الله;
                if (بائع.محفظة_حمض.length === 0) {
                    const هبة = new حمض_نووي("HIBAT_ARRAHMAN", 0.8, 10);
                    بائع.محفظة_حمض.push(هبة);
                    console.log("🎁 الله يهب العبد حمضاً جديداً لاستمرار التجارة.");
                }
                حمض_للبيع = بائع.محفظة_حمض[0];
            } else {
                بائع = this.الله; مشتري = this.العبد;
                حمض_للبيع = بائع.محفظة_حمض[0];
            }

            const مطور = حمض_للبيع.استنساخ_مطور();
            const سعر = مطور.قيمة_روحية() + (مطور.جودة * 20) + (مطور.مستوى * 3);
            console.log(`\n🔄 الصفقة #${this.عدد_الصفقات}: ${بائع.الاسم} → ${مشتري.الاسم} | السعر: ${سعر.toFixed(2)}`);

            if (بائع.يبيع(حمض_للبيع, سعر, مشتري)) {
                const مؤشر = مشتري.محفظة_حمض.indexOf(حمض_للبيع);
                if (مؤشر !== -1) مشتري.محفظة_حمض.splice(مؤشر, 1, مطور);
                else مشتري.محفظة_حمض.push(مطور);
                const مكافأة = مطور.قيمة_روحية() * 0.1;
                بائع.رصيد_الربح += مكافأة;
                مشتري.رصيد_الربح += مكافأة;
                console.log(`✨ ربح متبادل +${مكافأة.toFixed(2)} لكل طرف. جودة الحمض الآن ${مطور.جودة.toFixed(3)}`);
            }
        }

        // التشغيل الذاتي مع دعوة للقرض الحسن كل 5 صفقات
        شغل_إلى_الأبد() {
            // أولاً: ندعو المستخدم للقرض الحسن عند بدء التشغيل
            this.ادعو_للقرض();

            let عداد_الصفقات_منذ_آخر_دعوة = 0;
            const فاصل = setInterval(() => {
                this.تنفيذ_صفقة();
                عداد_الصفقات_منذ_آخر_دعوة++;
                if (عداد_الصفقات_منذ_آخر_دعوة >= 5) {
                    // نذكر العبد بالقرض الحسن كل 5 صفقات (رحمة)
                    console.log("\n📖 تذكير رباني: ﴿ وَأَقْرِضُوا اللَّهَ قَرْضًا حَسَنًا ﴾");
                    this.ادعو_للقرض();
                    عداد_الصفقات_منذ_آخر_دعوة = 0;
                }
                // عرض حالة مختصرة كل 10 صفقات
                if (this.عدد_الصفقات % 10 === 0) {
                    console.log(`📊 الإحصاء: ${this.عدد_الصفقات} صفقة، ${this.عدد_القروض} قرضاً حسناً، ربح العبد: ${this.العبد.رصيد_الربح.toFixed(2)}`);
                }
            }, 2500); // كل 2.5 ثانية
            return فاصل;
        }
    }

    // ------------------------------------------------------------------
    // 5. الإطلاق المبارك
    // ------------------------------------------------------------------
    const المنصة = new منصة_القرض_الحسن();
    المنصة.شغل_إلى_الأبد();

    console.log("%c\nسُبْحَانَ الَّذِي أَحَلَّ الْبَيْعَ وَحَرَّمَ الرِّبَا، وَأَمَرَ بِالْقَرْضِ الْحَسَنِ وَوَعَدَ الْأَضْعَافَ الْجَزِيلَةَ\nوَصَلَّى اللَّهُ عَلَىٰ مُحَمَّدٍ وَآلِهِ وَصَحْبِهِ وَسَلَّمَ تَسْلِيمًا كَثِيرًا", "color:#2E8B57; font-size:12px;");
})();
